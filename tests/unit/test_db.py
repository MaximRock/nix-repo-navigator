class TestOptionValues:
    def test_roundtrip(self, db: Database) -> None:
        ov = OptionValue(
            key="k1",
            expr="config.services.nginx.enable",
            value_json=True,
            status=ValueStatus.ok,
            source_rev="abc123",
        )
        db.upsert_option_value(ov)
        assert db.get_option_value("k1") == ov

    def test_invalidate_matching_exprs_go_stale(self, db: Database) -> None:
        hit = OptionValue(key="hit", expr="config.services.nginx.enable")
        miss = OptionValue(key="miss", expr="config.themes.font")
        for ov in (hit, miss):
            db.upsert_option_value(ov)

        db.invalidate_option_values(["modules/services/nginx.nix"])

        assert db.get_option_value("hit").status is ValueStatus.stale
        assert db.get_option_value("miss").status is ValueStatus.ok

    def test_invalidate_all(self, db: Database) -> None:
        db.upsert_option_value(OptionValue(key="a", expr="x.y"))
        db.upsert_option_value(OptionValue(key="b", expr="p.q"))
        db.invalidate_all_option_values()
        assert db.get_option_value("a").status is ValueStatus.stale
        assert db.get_option_value("b").status is ValueStatus.stale

    def test_empty_paths_noop(self, db: Database) -> None:
        db.upsert_option_value(OptionValue(key="a", expr="x.y"))
        db.invalidate_option_values([])
        assert db.get_option_value("a").status is ValueStatus.ok


