class TestFts5:
    def test_search_finds_by_name_token(self, db: Database) -> None:
        opt = Node(
            id="nix_option:services.nginx.enable",
            type=NodeType.nix_option,
            name="services.nginx.enable",
        )
        db.upsert_node(opt)
        results = db.search_fts5("nginx")
        assert [n.id for n in results] == [opt.id]

    def test_search_respects_limit_and_multi_tokens(self, db: Database) -> None:
        for i in range(3):
            db.upsert_node(
                Node(
                    id=f"o{i}",
                    type=NodeType.nix_option,
                    name=f"services.nginx.enable.opt{i}",
                )
            )
        hits = db.search_fts5("nginx enable", limit=2)  # tokens AND-ed
        assert len(hits) == 2

    def test_search_synced_on_update_and_delete(self, db: Database) -> None:
        node = Node(id="x1", type=NodeType.nix_function, name="mkService")
        db.upsert_node(node)
        assert db.search_fts5("mkservice")  # case-insensitive

        db.upsert_node(node.model_copy(update={"name": "makeService"}))
        assert db.search_fts5("makeservice")
        assert not db.search_fts5("mkservice")

        db.delete_file_nodes(None)  # no-op for NULL paths
        db._conn.execute("DELETE FROM nodes WHERE id='x1'")
        db._conn.commit()
        assert not db.search_fts5("makeservice")

    def test_search_garbage_query_is_safe(self, db: Database) -> None:
        assert db.search_fts5('"unbalanced') == []
        assert db.search_fts5("   ") == []


# -------------------------------------------------------------- persistence


class TestPersistence:
    def test_survives_reopen_and_reinit(self, tmp_path: Path) -> None:
        db_path = tmp_path / ".repo-navigator.db"
        first = Database(db_path)
        first.init_db()
        first.upsert_node(make_module("persist.nix"))
        first.inc_generation_id()
        first.close()

        second = Database(db_path)
        second.init_db()
        assert second.count_nodes() == 1
        assert second.get_generation_id() == 1
        assert second.get_node("nix:persist.nix") is not None
        second.close()

    def test_wal_enabled_on_file_db(self, tmp_path: Path) -> None:
        db = Database(tmp_path / "w.db")
        db.init_db()
        mode = db._conn.execute("PRAGMA journal_mode").fetchone()[0]
        assert mode.lower() == "wal"
        db.close()
