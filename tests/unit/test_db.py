# ------------------------------------------------------- flake_inputs/packages


class TestAuxTables:
    def test_flake_inputs(self, db: Database) -> None:
        db.upsert_flake_input("nixpkgs", "github:NixOS/nixpkgs", "rev1")
        db.upsert_flake_input("nixpkgs", "github:NixOS/nixpkgs", "rev2")
        inputs = db.get_flake_inputs()
        assert inputs == [{"name": "nixpkgs", "url": "github:NixOS/nixpkgs", "rev": "rev2"}]

    def test_packages(self, db: Database) -> None:
        db.upsert_package("ripgrep", "ripgrep", "14.1.0", "/nix/store/rg", {"license": "MIT"})
        pkgs = db.get_packages()
        assert pkgs[0]["attribute"] == "ripgrep"
        assert pkgs[0]["meta"] == {"license": "MIT"}

    def test_package_upsert_preserves_used_by(self, db: Database) -> None:
        db._conn.execute(
            "INSERT INTO package_index (attribute, used_by, first_seen, last_updated)"
            " VALUES ('rg', '[\"host1\"]', '2026-01-01', '2026-01-01')"
        )
        db._conn.commit()
        db.upsert_package("rg", "ripgrep", "14.1.0", None, {})
        row = db._conn.execute(
            "SELECT used_by FROM package_index WHERE attribute='rg'"
        ).fetchone()
        assert row[0] == '["host1"]'


