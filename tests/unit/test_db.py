def make_module(path: str = "modules/a.nix", **overrides) -> Node:
    defaults = dict(
        id=f"nix:{path}",
        type=NodeType.nix_module,
        name=path,
        path=path,
        lang="nix",
        metadata={"k": "v"},
    )
    defaults.update(overrides)
    return Node(**defaults)


# ---------------------------------------------------------------- lifecycle


class TestInit:
    def test_generation_starts_at_zero(self, db: Database) -> None:
        assert db.get_generation_id() == 0

    def test_inc_generation(self, db: Database) -> None:
        assert db.inc_generation_id() == 1
        assert db.inc_generation_id() == 2
        assert db.get_generation_id() == 2

    def test_schema_version_set(self, db: Database) -> None:
        version = db._conn.execute("PRAGMA user_version").fetchone()[0]
        assert version == CURRENT_SCHEMA_VERSION

    def test_reinit_is_idempotent(self, db: Database) -> None:
        db.upsert_node(make_module())
        db.init_db()  # must not wipe data or fail
        assert db.count_nodes() == 1
        assert db.get_generation_id() == 0


# -------------------------------------------------------------------- nodes


class TestNodes:
    def test_roundtrip_with_metadata(self, db: Database) -> None:
        node = make_module(metadata={"opt_type": "types.bool", "n": 42})
        db.upsert_node(node)
        loaded = db.get_node(node.id)
        # updated_at is regenerated by the DB on write
        assert loaded.model_dump(exclude={"updated_at"}) == node.model_dump(
            exclude={"updated_at"}
        )
        assert loaded.updated_at >= node.updated_at

    def test_get_missing_returns_none(self, db: Database) -> None:
        assert db.get_node("nope") is None

    def test_upsert_updates_but_keeps_created_at(self, db: Database) -> None:
        original = make_module(name="old.nix")
        db.upsert_node(original)

        renamed = original.model_copy(update={"name": "new.nix"})
        db.upsert_node(renamed)

        nodes = db.get_all_nodes()
        assert len(nodes) == 1
        assert nodes[0].name == "new.nix"
        assert nodes[0].created_at == original.created_at

    def test_delete_file_nodes_removes_edges(self, db: Database) -> None:
        a = make_module("modules/a.nix")
        b = make_module("modules/b.nix")
        c = make_module("modules/c.nix")
        for n in (a, b, c):
            db.upsert_node(n)
        db.upsert_edge(
            Edge(id="e1", source=a.id, target=b.id, type=EdgeType.imports)
        )
        db.upsert_edge(
            Edge(id="e2", source=c.id, target=b.id, type=EdgeType.imports)
        )

        db.delete_file_nodes(a.path)

        assert db.get_node(a.id) is None
        assert db.get_edge("e1") is None  # source deleted -> edge gone
        assert db.get_edge("e2") is not None  # untouched pair survives
        assert db.count_nodes() == 2

    def test_count_nodes(self, db: Database) -> None:
        assert db.count_nodes() == 0
        db.upsert_node(make_module())
        assert db.count_nodes() == 1


# -------------------------------------------------------------------- edges


class TestEdges:
    def test_roundtrip(self, db: Database) -> None:
        a, b = make_module("a.nix"), make_module("b.nix")
        db.upsert_node(a)
        db.upsert_node(b)
        edge = Edge(
            id="imports:a->b",
            source=a.id,
            target=b.id,
            type=EdgeType.imports,
            metadata={"line": 5},
            weight=2.0,
        )
        db.upsert_edge(edge)
        assert db.get_edge(edge.id) == edge
        assert db.get_all_edges() == [edge]

    def test_edge_requires_existing_endpoints(self, db: Database) -> None:
        with pytest.raises(sqlite3.IntegrityError):
            db.upsert_edge(
                Edge(id="x", source="ghost", target="also-ghost",
                     type=EdgeType.imports)
            )

    def test_get_edges_for_node_both_directions(self, db: Database) -> None:
        a = make_module("a.nix")
        b = make_module("b.nix")
        c = make_module("c.nix")
        for n in (a, b, c):
            db.upsert_node(n)
        e_ab = Edge(id="e_ab", source=a.id, target=b.id, type=EdgeType.imports)
        e_cb = Edge(id="e_cb", source=c.id, target=b.id, type=EdgeType.imports)
        db.upsert_edge(e_ab)
        db.upsert_edge(e_cb)

        found = {e.id for e in db.get_edges_for_node(b.id)}
        assert found == {"e_ab", "e_cb"}

    def test_get_edges_for_file_ownership_by_source(self, db: Database) -> None:
        a = make_module("modules/a.nix")
        b = make_module("modules/b.nix")
        db.upsert_node(a)
        db.upsert_node(b)
        owned = Edge(id="owned", source=a.id, target=b.id, type=EdgeType.imports)
        foreign = Edge(id="foreign", source=b.id, target=a.id, type=EdgeType.imports)
        db.upsert_edge(owned)
        db.upsert_edge(foreign)

        assert [e.id for e in db.get_edges_for_file(a.path)] == ["owned"]


